function C = coriolis_matrix(vVec,inertiaVec,dotVec)
% Coriolis matrix C(nu) = C_RB + C_A of the Fossen model; inertiaVec = [m; Iz],
% dotVec = [Xudot; Yvdot; Yrdot; Nrdot].
CA =               [0                       0       dotVec(2)*vVec(2)+dotVec(3)*vVec(3);...
                    0                       0               -dotVec(1)*vVec(1);...
      -dotVec(2)*vVec(2)-dotVec(3)*vVec(3)      dotVec(1)*vVec(1)                0];

CRB = [0                0     -inertiaVec(1)*vVec(2);...
       0                0       inertiaVec(1)*vVec(1);...
       inertiaVec(1)*vVec(2)     -inertiaVec(1)*vVec(1)     0];
C = CA + CRB;
end
